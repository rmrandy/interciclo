-- Script para crear las tablas del sistema de gestión de vuelos
-- Sistema MVP de Aerolínea con gestión completa de inventario y escalas

-- Eliminar tablas existentes si existen (en orden correcto por dependencias)
DROP TABLE IF EXISTS FLIGHT_FARES CASCADE;
DROP TABLE IF EXISTS FLIGHT_INVENTORY CASCADE;
DROP TABLE IF EXISTS FLIGHT_LEGS CASCADE;
DROP TABLE IF EXISTS AGENCIES CASCADE;

-- Actualizar tabla FLIGHTS con nuevos campos
-- Nota: En producción usar ALTER TABLE, aquí recreamos para simplificar
DROP TABLE IF EXISTS FLIGHTS_NEW CASCADE;

CREATE TABLE FLIGHTS_NEW (
    ID_FLIGHT NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FLIGHT_NUMBER VARCHAR2(10) NOT NULL UNIQUE,
    ROUTE_ID NUMBER(10) NOT NULL,
    AIRCRAFT_ID NUMBER(10) NOT NULL,
    DEPARTURE_DATE DATE NOT NULL,
    DEPARTURE_TIME TIMESTAMP NOT NULL,
    ARRIVAL_DATE DATE NOT NULL,
    ARRIVAL_TIME TIMESTAMP NOT NULL,
    BASE_PRICE NUMBER(10,2) NOT NULL,
    AVAILABLE_SEATS NUMBER(6) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    GATE VARCHAR2(10),
    TERMINAL VARCHAR2(20),
    CHECK_IN_START TIMESTAMP,
    CHECK_IN_END TIMESTAMP,
    BOARDING_TIME TIMESTAMP,
    -- Campos de auditoría
    CREATED_BY NUMBER(10) NOT NULL,
    UPDATED_BY NUMBER(10),
    CANCELLED_BY NUMBER(10),
    CANCELLATION_REASON VARCHAR2(500),
    CANCELLATION_DATE TIMESTAMP,
    CHANGE_LOG CLOB,
    NOTIFICATIONS_SENT NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- Constraints
    CONSTRAINT fk_flights_route FOREIGN KEY (ROUTE_ID) REFERENCES ROUTES(ID_ROUTE),
    CONSTRAINT fk_flights_aircraft FOREIGN KEY (AIRCRAFT_ID) REFERENCES AIRCRAFTS(ID_AIRCRAFT),
    CONSTRAINT fk_flights_created_by FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID_USER),
    CONSTRAINT fk_flights_updated_by FOREIGN KEY (UPDATED_BY) REFERENCES USERS(ID_USER),
    CONSTRAINT fk_flights_cancelled_by FOREIGN KEY (CANCELLED_BY) REFERENCES USERS(ID_USER),
    CONSTRAINT chk_flight_status CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT chk_available_seats CHECK (AVAILABLE_SEATS >= 0)
);

-- Crear tabla para escalas/stops en vuelos
CREATE TABLE FLIGHT_LEGS (
    ID_LEG NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FLIGHT_ID NUMBER(10) NOT NULL,
    AIRPORT_ID NUMBER(10) NOT NULL,
    LEG_ORDER NUMBER(2) NOT NULL,
    ARRIVAL_TIME TIMESTAMP NOT NULL,
    DEPARTURE_TIME TIMESTAMP NOT NULL,
    CONNECTION_TIME_MINUTES NUMBER(4),
    AIRCRAFT_CHANGE NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- Constraints
    CONSTRAINT fk_flight_legs_flight FOREIGN KEY (FLIGHT_ID) REFERENCES FLIGHTS_NEW(ID_FLIGHT) ON DELETE CASCADE,
    CONSTRAINT fk_flight_legs_airport FOREIGN KEY (AIRPORT_ID) REFERENCES AEROPUERTOS(ID_AEROPUERTO),
    CONSTRAINT chk_leg_order CHECK (LEG_ORDER > 0),
    CONSTRAINT chk_connection_time CHECK (CONNECTION_TIME_MINUTES >= 0),
    CONSTRAINT uk_flight_leg_order UNIQUE (FLIGHT_ID, LEG_ORDER)
);

-- Crear tabla para inventario por categoría
CREATE TABLE FLIGHT_INVENTORY (
    ID_INVENTORY NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FLIGHT_ID NUMBER(10) NOT NULL,
    SEAT_CATEGORY VARCHAR2(20) NOT NULL,
    TOTAL_SEATS NUMBER(6) NOT NULL,
    AVAILABLE_SEATS NUMBER(6) NOT NULL,
    RESERVED_SEATS NUMBER(6) DEFAULT 0 NOT NULL,
    SOLD_SEATS NUMBER(6) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- Constraints
    CONSTRAINT fk_inventory_flight FOREIGN KEY (FLIGHT_ID) REFERENCES FLIGHTS_NEW(ID_FLIGHT) ON DELETE CASCADE,
    CONSTRAINT chk_seat_category CHECK (SEAT_CATEGORY IN ('ECONOMY', 'BUSINESS', 'FIRST_CLASS')),
    CONSTRAINT chk_inventory_status CHECK (STATUS IN ('ACTIVE', 'CLOSED', 'SUSPENDED')),
    CONSTRAINT chk_total_seats CHECK (TOTAL_SEATS > 0),
    CONSTRAINT chk_available_seats_inv CHECK (AVAILABLE_SEATS >= 0),
    CONSTRAINT chk_reserved_seats CHECK (RESERVED_SEATS >= 0),
    CONSTRAINT chk_sold_seats CHECK (SOLD_SEATS >= 0),
    CONSTRAINT uk_flight_category UNIQUE (FLIGHT_ID, SEAT_CATEGORY)
);

-- Crear tabla para precios por categoría
CREATE TABLE FLIGHT_FARES (
    ID_FARE NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FLIGHT_ID NUMBER(10) NOT NULL,
    SEAT_CATEGORY VARCHAR2(20) NOT NULL,
    BASE_PRICE NUMBER(10,2) NOT NULL,
    CURRENCY VARCHAR2(3) DEFAULT 'GTQ' NOT NULL,
    TAXES NUMBER(10,2) DEFAULT 0,
    FEES NUMBER(10,2) DEFAULT 0,
    TOTAL_PRICE NUMBER(10,2) NOT NULL,
    PROMOTIONAL_PRICE NUMBER(10,2),
    PROMOTION_VALID_UNTIL TIMESTAMP,
    REFUNDABLE NUMBER(1) DEFAULT 1,
    CHANGEABLE NUMBER(1) DEFAULT 1,
    CHANGE_FEE NUMBER(10,2) DEFAULT 0,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- Constraints
    CONSTRAINT fk_fares_flight FOREIGN KEY (FLIGHT_ID) REFERENCES FLIGHTS_NEW(ID_FLIGHT) ON DELETE CASCADE,
    CONSTRAINT chk_fare_category CHECK (SEAT_CATEGORY IN ('ECONOMY', 'BUSINESS', 'FIRST_CLASS')),
    CONSTRAINT chk_fare_status CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'EXPIRED')),
    CONSTRAINT chk_base_price CHECK (BASE_PRICE > 0),
    CONSTRAINT chk_total_price CHECK (TOTAL_PRICE > 0),
    CONSTRAINT chk_taxes CHECK (TAXES >= 0),
    CONSTRAINT chk_fees CHECK (FEES >= 0),
    CONSTRAINT chk_change_fee CHECK (CHANGE_FEE >= 0),
    CONSTRAINT uk_flight_fare_category UNIQUE (FLIGHT_ID, SEAT_CATEGORY)
);

-- Crear tabla para agencias y clientes empresariales
CREATE TABLE AGENCIES (
    ID_AGENCY NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGENCY_CODE VARCHAR2(20) NOT NULL UNIQUE,
    COMPANY_NAME VARCHAR2(200) NOT NULL,
    CONTACT_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20),
    ADDRESS VARCHAR2(500),
    COUNTRY VARCHAR2(50),
    CITY VARCHAR2(100),
    DISCOUNT_PERCENTAGE NUMBER(5,2) DEFAULT 0,
    CREDIT_LIMIT NUMBER(15,2),
    CURRENT_BALANCE NUMBER(15,2) DEFAULT 0,
    COMMISSION_PERCENTAGE NUMBER(5,2) DEFAULT 0,
    PAYMENT_TERMS VARCHAR2(50) DEFAULT 'IMMEDIATE',
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    NOTIFICATION_PREFERENCES VARCHAR2(100) DEFAULT 'EMAIL',
    WS_ENDPOINT_URL VARCHAR2(500),
    WS_AUTH_TOKEN VARCHAR2(200),
    CONTRACT_START_DATE DATE,
    CONTRACT_END_DATE DATE,
    LAST_ACTIVITY TIMESTAMP,
    NOTES VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- Constraints
    CONSTRAINT chk_agency_status CHECK (STATUS IN ('ACTIVE', 'SUSPENDED', 'INACTIVE')),
    CONSTRAINT chk_notification_prefs CHECK (NOTIFICATION_PREFERENCES IN ('EMAIL', 'WS', 'BOTH')),
    CONSTRAINT chk_payment_terms CHECK (PAYMENT_TERMS IN ('IMMEDIATE', 'NET_30', 'NET_60')),
    CONSTRAINT chk_discount_percentage CHECK (DISCOUNT_PERCENTAGE >= 0 AND DISCOUNT_PERCENTAGE <= 100),
    CONSTRAINT chk_commission_percentage CHECK (COMMISSION_PERCENTAGE >= 0 AND COMMISSION_PERCENTAGE <= 100)
);

