-- Triggers para actualizar UPDATED_AT automáticamente
CREATE OR REPLACE TRIGGER trg_flights_updated_at
    BEFORE UPDATE ON FLIGHTS_NEW
    FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_flight_legs_updated_at
    BEFORE UPDATE ON FLIGHT_LEGS
    FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
    -- Calcular tiempo de conexión automáticamente
    IF :NEW.ARRIVAL_TIME IS NOT NULL AND :NEW.DEPARTURE_TIME IS NOT NULL THEN
        :NEW.CONNECTION_TIME_MINUTES := EXTRACT(HOUR FROM (:NEW.DEPARTURE_TIME - :NEW.ARRIVAL_TIME)) * 60 +
                                       EXTRACT(MINUTE FROM (:NEW.DEPARTURE_TIME - :NEW.ARRIVAL_TIME));
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_inventory_updated_at
    BEFORE UPDATE ON FLIGHT_INVENTORY
    FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
    -- Recalcular asientos disponibles
    :NEW.AVAILABLE_SEATS := :NEW.TOTAL_SEATS - :NEW.RESERVED_SEATS - :NEW.SOLD_SEATS;
    IF :NEW.AVAILABLE_SEATS < 0 THEN
        :NEW.AVAILABLE_SEATS := 0;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_fares_updated_at
    BEFORE UPDATE ON FLIGHT_FARES
    FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
    -- Recalcular precio total
    :NEW.TOTAL_PRICE := :NEW.BASE_PRICE + NVL(:NEW.TAXES, 0) + NVL(:NEW.FEES, 0);
END;
/

CREATE OR REPLACE TRIGGER trg_agencies_updated_at
    BEFORE UPDATE ON AGENCIES
    FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
END;
/

